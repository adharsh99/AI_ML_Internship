# Module 1 - Strings

name = "Thanniru Adarsh"

print("Original:", name)

print("Uppercase:", name.upper())
print("Lowercase:", name.lower())

print("Length:", len(name))

print("Replace:", name.replace("Adarsh", "AI Intern"))

words = name.split()

print("Words:", words)

print("First Character:", name[0])
print("Last Character:", name[-1])